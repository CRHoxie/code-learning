/*求1+1/2+1/4+1/6+...+1/N的和。
本题要求：任意输入一个正偶数N，计算分母为偶数的分式的和，如输入6，则计算1+1/2+1/4+1/6，N的取值范围为[2,100]。输出最终的计算结果，保留两位小数。

输入格式:
在一行中给出一个正偶数N。

输出格式:
在一行中输出计算结果，精确到小数点后两位。*/

#include<stdio.h>
int main(){
    int N;
    double sum = 0.00;
    scanf("%d",&N);
    for(int i=1;i<=N;i++){
        if(i%2!=0) continue;
        sum+=1/(1.0*i);
    }
    printf("%.2lf",sum+1);
}