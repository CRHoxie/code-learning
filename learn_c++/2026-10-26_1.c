/*小林打算向朋友借钱，请输入一个浮点数m和一个整数n，分别表示他想借的钱数和借期，程序输出他的意图。

输入格式:
输入在一行中给出1个浮点数和1个整数，二者均大于0。

输出格式:
输出的钱数保留两位小数，格式如下所示：

你好，可以借我XX.XX元钱吗？

X天后一定还！*/
